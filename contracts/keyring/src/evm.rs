//! EIP-1559 transaction construction for EVM chains.
//!
//! # Why the contract builds the transaction
//!
//! Invariants 5–8 require that the bytes which get signed are derived from
//! fields policy approved, and that no caller can smuggle a different recipient
//! or amount into them. That is only true if the transaction is assembled here,
//! from validated state, rather than accepted as a preimage from the caller.
//!
//! So this module takes the already-validated destination and amount plus the
//! gas parameters, and produces the exact 32 bytes the MPC signer signs. There
//! is no code path that accepts a caller-supplied hash, calldata or RLP blob.
//!
//! # The fee is computed, never supplied
//!
//! An EIP-1559 transaction's maximum cost is `gas_limit * max_fee_per_gas`.
//! Earlier the caller passed a `fee` field that policy checked, which was
//! unsound: a caller could declare a small fee and still sign a transaction
//! authorising a large one. [`EvmParams::max_fee_wei`] derives the fee from the
//! same numbers that go into the signed transaction, so the value policy checks
//! and the value the transaction can actually spend are the same number by
//! construction (invariant 9).
//!
//! # RLP
//!
//! The encoder below is deliberately minimal and handles only what an EIP-1559
//! transaction needs. Correctness is not argued from the code: the resulting
//! hashes are checked against fixtures generated by viem in
//! `tests/evm_transaction.rs`.

use near_sdk::{env, near};

/// Base Sepolia. Verified against the chain: `eth_chainId` returns `0x14a34`.
pub const BASE_SEPOLIA_CHAIN_ID: u64 = 84_532;

/// Intrinsic gas for a plain value transfer with no calldata.
///
/// A lower limit cannot produce a valid transfer, so it is rejected rather than
/// signed into a transaction that is guaranteed to fail.
pub const MIN_TRANSFER_GAS: u64 = 21_000;

/// Upper bound on an accepted gas limit.
///
/// Keyring only builds plain value transfers, which cost exactly
/// [`MIN_TRANSFER_GAS`]. A larger limit raises the fee ceiling without being
/// able to buy anything, so an absurd limit is a mistake or an attempt to burn
/// the budget on fees. Bounded generously rather than pinned to 21000 so that
/// a caller padding slightly is not refused.
pub const MAX_TRANSFER_GAS: u64 = 200_000;

/// Gas parameters for an EVM transfer, supplied by the caller.
///
/// These come from the semi-trusted SDK/relayer, which reads them from an RPC.
/// Wrong values cause a transaction that fails, stalls, or overpays miners —
/// all within the fee cap — but none of them can change the recipient or the
/// amount, because those come from policy (threat T6).
#[near(serializers = [json, borsh])]
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct EvmParams {
    /// Sender nonce. The contract cannot verify freshness; a stale nonce makes
    /// the broadcast fail, which is a relayer concern (CLAUDE.md §7).
    pub nonce: near_sdk::json_types::U64,
    pub gas_limit: near_sdk::json_types::U64,
    pub max_fee_per_gas: near_sdk::json_types::U128,
    pub max_priority_fee_per_gas: near_sdk::json_types::U128,
}

/// Why a set of EVM parameters was rejected.
#[derive(Debug, PartialEq, Eq)]
pub enum EvmParamsError {
    GasLimitTooLow,
    GasLimitTooHigh,
    PriorityFeeAboveMaxFee,
    ZeroMaxFee,
    FeeOverflow,
}

impl EvmParamsError {
    pub fn message(&self) -> String {
        match self {
            EvmParamsError::GasLimitTooLow => {
                format!("gas_limit must be at least {MIN_TRANSFER_GAS}")
            }
            EvmParamsError::GasLimitTooHigh => {
                format!("gas_limit must not exceed {MAX_TRANSFER_GAS}")
            }
            EvmParamsError::PriorityFeeAboveMaxFee => {
                "max_priority_fee_per_gas must not exceed max_fee_per_gas".to_string()
            }
            EvmParamsError::ZeroMaxFee => "max_fee_per_gas must be greater than zero".to_string(),
            EvmParamsError::FeeOverflow => "gas_limit * max_fee_per_gas overflows u128".to_string(),
        }
    }
}

impl EvmParams {
    /// Validates the parameters against EIP-1559's own rules and our bounds.
    pub fn validate(&self) -> Result<(), EvmParamsError> {
        if self.max_fee_per_gas.0 == 0 {
            return Err(EvmParamsError::ZeroMaxFee);
        }
        if self.gas_limit.0 < MIN_TRANSFER_GAS {
            return Err(EvmParamsError::GasLimitTooLow);
        }
        if self.gas_limit.0 > MAX_TRANSFER_GAS {
            return Err(EvmParamsError::GasLimitTooHigh);
        }
        // EIP-1559 requires the tip to be no greater than the total fee cap.
        if self.max_priority_fee_per_gas.0 > self.max_fee_per_gas.0 {
            return Err(EvmParamsError::PriorityFeeAboveMaxFee);
        }
        self.max_fee_wei()?;
        Ok(())
    }

    /// The most this transaction can spend on fees, in wei.
    ///
    /// This is the number policy checks against the fee cap. It is the worst
    /// case: the actual cost is `gas_used * effective_gas_price`, which is
    /// never higher. Checking the ceiling means a signed transaction can never
    /// cost more than the cap allowed, whatever the network does.
    pub fn max_fee_wei(&self) -> Result<u128, EvmParamsError> {
        u128::from(self.gas_limit.0)
            .checked_mul(self.max_fee_per_gas.0)
            .ok_or(EvmParamsError::FeeOverflow)
    }
}

// ------------------------------------------------------------------------ RLP

/// Encodes a byte string per RLP rules.
pub fn rlp_bytes(bytes: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len() + 9);
    if bytes.len() == 1 && bytes[0] <= 0x7f {
        // A single low byte is its own encoding.
        out.push(bytes[0]);
    } else if bytes.len() <= 55 {
        out.push(0x80 + bytes.len() as u8);
        out.extend_from_slice(bytes);
    } else {
        let len = to_be_minimal(bytes.len() as u128);
        out.push(0xb7 + len.len() as u8);
        out.extend_from_slice(&len);
        out.extend_from_slice(bytes);
    }
    out
}

/// Encodes an already-encoded sequence of items as an RLP list.
pub fn rlp_list(payload: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(payload.len() + 9);
    if payload.len() <= 55 {
        out.push(0xc0 + payload.len() as u8);
    } else {
        let len = to_be_minimal(payload.len() as u128);
        out.push(0xf7 + len.len() as u8);
        out.extend_from_slice(&len);
    }
    out.extend_from_slice(payload);
    out
}

/// Big-endian bytes with leading zeros stripped. Zero encodes as empty.
///
/// RLP has no concept of a fixed-width integer: numbers are minimal big-endian
/// byte strings, and zero is the empty string, not `0x00`.
pub fn to_be_minimal(value: u128) -> Vec<u8> {
    if value == 0 {
        return Vec::new();
    }
    let bytes = value.to_be_bytes();
    let first = bytes
        .iter()
        .position(|b| *b != 0)
        .unwrap_or(bytes.len() - 1);
    bytes[first..].to_vec()
}

/// Encodes an integer as an RLP byte string.
pub fn rlp_uint(value: u128) -> Vec<u8> {
    rlp_bytes(&to_be_minimal(value))
}

// ------------------------------------------------------------- transaction

/// An EIP-1559 (type 2) transfer, built from validated fields.
///
/// `data` is intentionally absent: Keyring builds plain value transfers only.
/// There is no field for calldata, so no caller can attach any. ERC-20
/// transfers would require composing a `transfer` call here from a validated
/// token address, recipient and amount (invariant 7); that is not implemented.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Eip1559Transfer {
    pub chain_id: u64,
    pub nonce: u64,
    pub max_priority_fee_per_gas: u128,
    pub max_fee_per_gas: u128,
    pub gas_limit: u64,
    /// Recipient, exactly as policy approved it.
    pub to: [u8; 20],
    /// Value in wei, exactly as policy approved it.
    pub value: u128,
}

impl Eip1559Transfer {
    /// The RLP payload shared by the signing preimage and the signed encoding.
    fn base_fields(&self) -> Vec<u8> {
        let mut p = Vec::new();
        p.extend_from_slice(&rlp_uint(u128::from(self.chain_id)));
        p.extend_from_slice(&rlp_uint(u128::from(self.nonce)));
        p.extend_from_slice(&rlp_uint(self.max_priority_fee_per_gas));
        p.extend_from_slice(&rlp_uint(self.max_fee_per_gas));
        p.extend_from_slice(&rlp_uint(u128::from(self.gas_limit)));
        p.extend_from_slice(&rlp_bytes(&self.to));
        p.extend_from_slice(&rlp_uint(self.value));
        p.extend_from_slice(&rlp_bytes(&[])); // data: empty
        p.extend_from_slice(&rlp_list(&[])); // access_list: empty
        p
    }

    /// The unsigned transaction: `0x02 || rlp([...])`.
    pub fn unsigned_encoding(&self) -> Vec<u8> {
        let mut out = vec![0x02];
        out.extend_from_slice(&rlp_list(&self.base_fields()));
        out
    }

    /// The 32 bytes the MPC signer signs.
    pub fn signing_hash(&self) -> [u8; 32] {
        let digest = env::keccak256(&self.unsigned_encoding()[..]);
        let mut out = [0u8; 32];
        out.copy_from_slice(&digest);
        out
    }

    /// The broadcastable transaction, given a signature.
    ///
    /// Provided so tests can assert that the signed encoding still carries the
    /// approved recipient and value. The SDK assembles the same bytes for
    /// broadcast; both are checked against viem fixtures.
    pub fn signed_encoding(&self, r: &[u8; 32], s: &[u8; 32], y_parity: u8) -> Vec<u8> {
        let mut p = self.base_fields();
        p.extend_from_slice(&rlp_uint(u128::from(y_parity)));
        // r and s are encoded as minimal integers, not fixed 32-byte strings.
        p.extend_from_slice(&rlp_bytes(strip_leading_zeros(r)));
        p.extend_from_slice(&rlp_bytes(strip_leading_zeros(s)));
        let mut out = vec![0x02];
        out.extend_from_slice(&rlp_list(&p));
        out
    }
}

fn strip_leading_zeros(bytes: &[u8; 32]) -> &[u8] {
    let first = bytes.iter().position(|b| *b != 0).unwrap_or(bytes.len());
    &bytes[first..]
}

/// Parses a normalised `0x`-prefixed address into 20 raw bytes.
///
/// Returns `None` for anything not exactly 20 hex-encoded bytes, so a malformed
/// address can never reach transaction construction.
pub fn address_bytes(normalized: &str) -> Option<[u8; 20]> {
    let hex = normalized.strip_prefix("0x")?;
    if hex.len() != 40 {
        return None;
    }
    let mut out = [0u8; 20];
    for (i, chunk) in hex.as_bytes().chunks(2).enumerate() {
        let hi = (chunk[0] as char).to_digit(16)?;
        let lo = (chunk[1] as char).to_digit(16)?;
        out[i] = (hi * 16 + lo) as u8;
    }
    Some(out)
}
