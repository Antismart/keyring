#!/usr/bin/env node
/**
 * Generate EIP-1559 reference fixtures with viem.
 *
 * CLAUDE.md §7 requires the contract's transaction hash to match an
 * independently computed reference. viem is that reference: it is a widely
 * used, independently maintained implementation, and it shares no code with
 * the Rust encoder in `contracts/keyring/src/evm.rs`.
 *
 * The output is committed to `contracts/keyring/tests/fixtures/eip1559.json`
 * and asserted by `contracts/keyring/tests/evm_transaction.rs`. Regenerating
 * it and finding a diff means one of the two implementations changed.
 *
 *   node scripts/gen-evm-fixtures.mjs          # write the fixture
 *   node scripts/gen-evm-fixtures.mjs --check  # fail if it would change
 */

import { readFileSync, writeFileSync } from "node:fs";
import { keccak256, serializeTransaction } from "viem";

const BASE_SEPOLIA = 84532;

/** Cases chosen to exercise RLP's awkward edges, not just a happy path. */
const cases = [
  {
    name: "typical_transfer",
    note: "0.001 ETH, nonce 0, minimum gas",
    tx: {
      chainId: BASE_SEPOLIA,
      nonce: 0,
      to: "0x1111111111111111111111111111111111111111",
      value: 1000000000000000n,
      gas: 21000n,
      maxFeePerGas: 1000000000n,
      maxPriorityFeePerGas: 1000000n,
    },
  },
  {
    name: "nonzero_nonce",
    note: "nonce above the single-byte RLP boundary",
    tx: {
      chainId: BASE_SEPOLIA,
      nonce: 128,
      to: "0x2222222222222222222222222222222222222222",
      value: 1n,
      gas: 21000n,
      maxFeePerGas: 2000000000n,
      maxPriorityFeePerGas: 0n,
    },
  },
  {
    name: "zero_priority_fee",
    note: "zero must encode as the empty string, not 0x00",
    tx: {
      chainId: BASE_SEPOLIA,
      nonce: 1,
      to: "0x3333333333333333333333333333333333333333",
      value: 12345n,
      gas: 21000n,
      maxFeePerGas: 7n,
      maxPriorityFeePerGas: 0n,
    },
  },
  {
    name: "large_values_long_payload",
    note: "forces the >55-byte RLP list header",
    tx: {
      chainId: BASE_SEPOLIA,
      nonce: 4294967295,
      to: "0x4444444444444444444444444444444444444444",
      value: 340282366920938463463374607431768211455n, // u128 max
      gas: 200000n,
      maxFeePerGas: 340282366920938463463374607431768211455n,
      maxPriorityFeePerGas: 340282366920938463463374607431768211454n,
    },
  },
  {
    name: "single_byte_boundary",
    note: "0x7f encodes as itself, 0x80 needs a length prefix",
    tx: {
      chainId: BASE_SEPOLIA,
      nonce: 127,
      to: "0x5555555555555555555555555555555555555555",
      value: 128n,
      gas: 21000n,
      maxFeePerGas: 128n,
      maxPriorityFeePerGas: 127n,
    },
  },
];

/** A fixed signature, used only to check the signed encoding's shape. */
const SIGNATURE = {
  r: "0x1111111111111111111111111111111111111111111111111111111111111111",
  s: "0x2222222222222222222222222222222222222222222222222222222222222222",
  yParity: 1,
};

const fixtures = cases.map(({ name, note, tx }) => {
  const unsigned = serializeTransaction({ ...tx, type: "eip1559" });
  const signed = serializeTransaction({ ...tx, type: "eip1559" }, SIGNATURE);
  return {
    name,
    note,
    chain_id: tx.chainId,
    nonce: Number(tx.nonce),
    to: tx.to,
    value: tx.value.toString(),
    gas_limit: tx.gas.toString(),
    max_fee_per_gas: tx.maxFeePerGas.toString(),
    max_priority_fee_per_gas: tx.maxPriorityFeePerGas.toString(),
    unsigned_rlp: unsigned,
    signing_hash: keccak256(unsigned),
    signature: SIGNATURE,
    signed_rlp: signed,
  };
});

const output =
  JSON.stringify(
    {
      _comment:
        "Generated by scripts/gen-evm-fixtures.mjs using viem. Do not edit by hand.",
      viem_version: JSON.parse(
        readFileSync(new URL("../node_modules/viem/package.json", import.meta.url)),
      ).version,
      fixtures,
    },
    null,
    2,
  ) + "\n";

const target = new URL("../contracts/keyring/tests/fixtures/eip1559.json", import.meta.url);

if (process.argv.includes("--check")) {
  const existing = readFileSync(target, "utf8");
  if (existing !== output) {
    console.error("FAIL: committed fixtures differ from freshly generated ones");
    process.exit(1);
  }
  console.log(`OK: ${fixtures.length} fixtures match viem ${JSON.parse(output).viem_version}`);
} else {
  writeFileSync(target, output);
  console.log(`wrote ${fixtures.length} fixtures to ${target.pathname}`);
}
